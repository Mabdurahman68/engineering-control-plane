import type { PublishContext } from './ports.ts';
import type { Engine } from './engine.ts';
import { integrationBranch, tipOf } from './steps-integrate.ts';

function blocked(e: Engine, reason: string, frozenTree: string | null): boolean {
  e.decide(
    'DP-PUBLISH',
    null,
    'hold_push',
    null,
    'PUSHING',
    'PUSH_BLOCKED',
    { signatures: [reason.slice(0, 80)] },
    frozenTree,
  );
  e.runTo('PUSH_BLOCKED', 'push_blocked', { reason });
  return true;
}

// One commit, frozen first. Everything reads that SHA, and the push uses it, not a branch name.
// Each crash window resolves from the remote's state: it never pushes twice, or opens a second PR.
export async function stepPushing(e: Engine): Promise<boolean> {
  const pub = e.p.publisher;
  const p = e.spec.publish;
  if (!pub || !p) return blocked(e, 'no publisher', null);
  const reviewedTree = e.s.verify.tree ?? (await e.p.git.treeOf(tipOf(e)));
  const ctx: PublishContext = {
    runId: e.o.runId,
    spec: e.spec,
    branch: integrationBranch(e),
    destination: `ecp/${e.o.runId}/integration`,
    candidate: tipOf(e),
    reviewedTree,
    acceptedBase: e.s.publish.accepted_base,
    prTitle: `${e.spec.spec_id}: ${e.spec.title}`,
    prBody: `Generated by ecp, run ${e.o.runId}. Not merged: merging is the owner's. This repository may be public.`,
  };
  if (!e.s.publish.frozen_sha) {
    const { sha } = await pub.freeze(ctx);
    e.append('push.sha_frozen', null, { sha });
    return true;
  }
  const sha = e.s.publish.frozen_sha;
  if (!e.s.publish.pushed) {
    // A crash may have fallen between the push and its record: ask the remote first.
    const at = await pub.remoteAt(ctx);
    if (e.s.publish.push_intent && at === sha) {
      e.append('push.done', null, { sha, recovered: true });
      return true;
    }
    e.append('push.gate_started', null, { sha });
    const gate = await pub.gates(ctx, sha);
    if (!gate.ok) {
      const reason = gate.failures
        .map((f) => `${f.id}: ${f.detail}`)
        .join('; ')
        .slice(0, 600);
      e.append('push.gate_failed', null, {
        sha,
        failures: gate.failures,
        results: gate.results,
        reason,
      });
      return blocked(e, reason, reviewedTree);
    }
    e.append('tree.identity_checked', null, {
      phase: 'push',
      ok: true,
      tree: reviewedTree,
      results: gate.results,
    });
    e.decide('DP-PUBLISH', null, 'push', ctx.destination, 'PUSHING', 'PR_OPENED', {}, reviewedTree);
    e.append('push.intent', null, { sha, destination: ctx.destination });
    const pushed = await pub.push(ctx, sha);
    if (!pushed.ok) {
      e.append('push.rejected', null, { sha, reason: pushed.detail });
      e.runTo('PUSH_BLOCKED', 'push_blocked', { reason: pushed.detail });
      return true;
    }
    e.append('push.done', null, { sha });
    return true;
  }
  if (!e.s.publish.verified) {
    const v = await pub.verifyPush(ctx, sha);
    if (!v.ok) {
      e.append('push.rejected', null, { sha, reason: v.detail });
      e.runTo('PUSH_BLOCKED', 'push_blocked', { reason: v.detail });
      return true;
    }
    e.append('push.verified', null, { sha, destination: ctx.destination });
    return true;
  }
  if (e.s.publish.pr_validated) {
    e.runTo('PR_OPENED', 'published', { reason: 'draft PR open' });
    return true;
  }
  // Before any create: a crash may have fallen after the PR was made.
  let listed = await pub.listPrs(ctx, sha);
  if (!listed.ok) {
    e.append('pr.validation_failed', null, { reason: listed.detail });
    e.runTo('PUSH_BLOCKED', 'push_blocked', { reason: `PR: ${listed.detail}` });
    return true;
  }
  if (listed.prs.length === 0) {
    e.append('pr.intent', null, { sha });
    const made = await pub.openPr(ctx, sha);
    if (!made.ok) {
      e.append('pr.validation_failed', null, { reason: made.detail });
      e.runTo('PUSH_BLOCKED', 'push_blocked', { reason: `PR: ${made.detail}` });
      return true;
    }
    e.append('pr.opened', null, { url: made.url });
    listed = await pub.listPrs(ctx, sha);
  }
  const valid = pub.validatePr(ctx, sha, listed.prs);
  if (!valid.ok) {
    e.append('pr.validation_failed', null, { reason: valid.detail, url: valid.url });
    e.runTo('PUSH_BLOCKED', 'push_blocked', { reason: `PR: ${valid.detail}` });
    return true;
  }
  if (!e.s.publish.pr_url) e.append('pr.opened', null, { url: valid.url, recovered: true });
  e.append('pr.validated', null, { url: valid.url });
  return true;
}
