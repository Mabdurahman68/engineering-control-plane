const pairs = (text: string) =>
  text
    .split(';')
    .map((x) => x.trim().split(/\s+/))
    .filter((x) => x.length === 2)
    .map(([a, b]) => `${a}>${b}`);

describe('tables against an inventory typed from the specification', () => {
  it('has every run row the specification lists', () => {
    const have = new Set(RUN_ROWS.map((r) => `${r.from}>${r.to}`));
    expect(pairs(RUN_SPEC).filter((p) => !have.has(p))).toEqual([]);
  });
  it('has every task row the specification lists', () => {
    const have = new Set(TASK_ROWS.map((r) => `${r.from}>${r.to}`));
    expect(pairs(TASK_SPEC).filter((p) => !have.has(p))).toEqual([]);
  });
});
